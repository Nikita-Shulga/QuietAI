// Russian typography: a dash never starts a line, so the space before it doesn't break.
const keepDash=text=>text.replace(/ \u2014/g,'\u00a0\u2014');
for(const [key,value] of Object.entries(ru))ru[key]=typeof value==='string'?keepDash(value):Object.fromEntries(Object.entries(value).map(([form,text])=>[form,keepDash(text)]));

const strings={en,ru};
let current='en';
const pluralRules={};
function normalize(language){return LANGUAGES.includes(language)?language:'en';}
function setLanguage(language){current=normalize(language);return current;}
function language(){return current;}
function fill(text,params){return params?String(text).replace(/\{(\w+)\}/g,(whole,name)=>name in params?String(params[name]):whole):String(text);}
function pick(value,count,lang){
  if(!value||typeof value!=='object')return value;
  const rules=pluralRules[lang]||(pluralRules[lang]=new Intl.PluralRules(lang));
  return value[rules.select(Number(count))]??value.other??value.one;
}
// tr('key',{name:value}) in the current language; a missing Russian key falls back to English.
function tr(key,params,lang){
  lang=normalize(lang||current);
  let value=strings[lang][key];if(value===undefined){lang='en';value=strings.en[key];}
  if(value===undefined)return key;
  return fill(pick(value,params&&params.count,lang),params);
}
function has(key){return key in en;}
function number(value,options,lang){try{return new Intl.NumberFormat(normalize(lang||current),options).format(value);}catch{return String(value);}}

// ——— Monitor text (display only) ———
// Placeholders that may themselves be translated (an app name, Claude's "input").
const NESTED=new Set(['app','what']);
const SHAPES={id:'[0-9A-Fa-f][0-9A-Fa-f-]{0,63}',count:'\\d+',code:'-?\\d+'};
let compiled=null;
function compile(){
  compiled={exact:new Map(),patterns:[]};
  for(const key of Object.keys(en)){
    if(!key.startsWith('m.'))continue;
    const text=en[key],names=[];
    if(!/\{\w+\}/.test(text)){compiled.exact.set(text,key);continue;}
    const source=text.split(/(\{\w+\})/).map(part=>{const m=/^\{(\w+)\}$/.exec(part);if(!m)return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');names.push(m[1]);return '('+(SHAPES[m[1]]||'.+?')+')';}).join('');
    compiled.patterns.push({key,names,re:new RegExp('^'+source+'$')});
  }
  return compiled;
}
// Chat titles are mostly the user's own text, so only the generated fallback names are translated.
const TITLES=new Set(['m.chat','m.claudeChat','m.appWorking','m.appReplyWorking','m.appTasksWorking','m.appTabWorking']);
function monitorText(text,lang,only){
  lang=normalize(lang||current);
  if(lang==='en'||typeof text!=='string'||!text)return text;
  const table=compiled||compile();
  const exact=table.exact.get(text);if(exact&&(!only||only.has(exact)))return tr(exact,null,lang);
  for(const {key,names,re} of table.patterns){
    if(only&&!only.has(key))continue;
    const m=re.exec(text);if(!m)continue;
    const params={};names.forEach((name,i)=>{const v=m[i+1];params[name]=NESTED.has(name)&&table.exact.has(v)?tr(table.exact.get(v),null,lang):v;});
    return tr(key,params,lang);
  }
  return text;
}
function chatTitle(text,lang){return monitorText(text,lang,TITLES);}

return{NAMES,LANGUAGES,strings,normalize,setLanguage,language,tr,has,number,monitorText,chatTitle};
